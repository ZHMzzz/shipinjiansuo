def main():
    path = OUT / 'design.json'
    if path.exists():
        raise SystemExit('Refusing to overwrite frozen design')
    cases = []
    for kind, rows in [('short', SHORT), ('paragraph', PARAGRAPHS)]:
        for i, (query, criteria) in enumerate(rows, 1):
            cases.append({'id': f'{kind[0]}{i:02}', 'kind': kind, 'query': query, 'criteria': criteria})
    design = {'system_prompt': PROMPT, 'cases': cases,
              'warmup': '海边有人放风筝。', 'repeats': ['s02', 's12', 'p01', 'p08'],
              'decoding': {'do_sample': False, 'enable_thinking': False, 'max_new_tokens': 640},
              'rubric': '严格正确=JSON结构正确且全部参考语义点通过；逐点代理人工审阅，不按字面一致；无新增必需约束；独立场景/动作必须拆分。不是盲评或独立人工标注。'}
    path.write_text(json.dumps(design, ensure_ascii=False, indent=2) + '\n')
    print(f'Frozen {len(cases)} cases before inference: {path}')

if __name__ == '__main__':
    main()
